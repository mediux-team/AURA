func AddRoutes(r *chi.Mux) {
	// If the config is not valid, only allow access to the /onboarding routes
	if !(config.Loaded && config.Valid) {
		if config.Loaded && !config.Current.IsSetUp() {
			logging.LOGGER.Info().Timestamp().Msg("aura is not set up yet, adding setup routes only")
		} else {
			logging.LOGGER.Warn().Timestamp().Bool("loaded", config.Loaded).Bool("valid", config.Valid).Msg("Configuration invalid or not loaded, adding setup routes only")
		}
		// Without a login, setup is protected by the setup code, printed once the config is loaded
		if config.Loaded && !config.AuthEnabled() {
			logging.LOGGER.Warn().Timestamp().Msgf("aura is in setup mode. Enter this setup code on the setup page: %s", config.SetupCode())
		}
		addOnboardingRoutes(r)
		return
	} else {
		logging.LOGGER.Info().Timestamp().Msg("Configuration loaded and valid, adding full routes")
	}

	// Swagger Docs Route
	r.Get("/swagger/*", httpSwagger.WrapHandler)

	r.Route("/api", func(r chi.Router) {

		// Authenticator applies to every route below and is the single source of truth for what's
		// actually public - see publicPathPrefixes in routing/middleware/authenticator.go. It also
		// handles the Sonarr/Radarr webhook's Basic-Auth requirement and the X-Api-Key/session-cookie
		// split, so routes don't need to be manually split into separate public/protected groups.
		r.Use(middleware.Authenticator)

		// Base Routes
		r.Get("/", routes_base.HealthCheck)
		r.Get("/health", routes_base.HealthCheck)

		// Login - starts a browser session
		r.Post("/login", routes_auth.AttemptLogin)

		// Logout - clears the browser session cookie
		r.Post("/logout", routes_auth.Logout)

		// OIDC (SSO) login flow
		r.Get("/auth/oidc/login", routes_auth.OIDCLoginRedirect)
		r.Get("/auth/oidc/callback", routes_auth.OIDCCallback)

		// Search - Media Items, Saved Sets and MediUX Users
		r.Get("/search", routes_search.HandleSearch)

		// Sonarr/Radarr Webhook
		r.Post("/sonarr/webhook", routes_sonarr_radarr.SonarrWebhookHandler)

		// Config Routes
		r.Route("/config", func(r chi.Router) {
			r.Get("/", routes_config.GetAppConfigStatus)
			r.Get("/stream", routes_config.StreamAppConfigStatus)
			r.Get("/template-variables", routes_config.GetNotificationTemplateVariables)
			r.Post("/", routes_config.UpdateAppConfig)
			r.Get("/export", routes_config.ExportAppConfig)
			r.Post("/import", routes_config.ImportAppConfig)
			r.Post("/main-media-server/preview", routes_config.PreviewMainMediaServerSwitch)
			r.Post("/main-media-server", routes_config.SwitchMainMediaServer)
			r.Patch("/{section}", routes_config.UpdateAppConfigSection)
			r.Get("/auth-methods", routes_auth.GetAuthMethods)
			r.Post("/auth/api-key", routes_auth.GenerateAPIKey)
		})

		// Database Routes
		r.Route("/db", func(r chi.Router) {
			r.Get("/", routes_db.GetAllItems)
			r.Post("/", routes_db.AddNewItemToDB)
			r.Patch("/", routes_db.UpdateItemInDB)
			r.Delete("/", routes_db.DeleteItemFromDB)
			r.Patch("/ignore", routes_db.IgnoreItemInDB)
			r.Patch("/ignore/stop", routes_db.StopIgnoringItemInDB)
			r.Post("/force-check", routes_db.AutoDownloadForceCheck)
			r.Get("/creators", routes_db.GetSavedSetCreators)
			r.Get("/backups", routes_db.GetDatabaseBackups)
			r.Post("/backups", routes_db.CreateDatabaseBackup)
		})

		// Download Routes
		r.Route("/download", func(r chi.Router) {
			// Download
			r.Post("/image/item", routes_download.DownloadImageFileForMediaItem)
			r.Post("/image/collection", routes_download.DownloadImageFileForCollectionItem)
			r.Post("/favorite-creators", routes_download.DownloadFromFavoriteCreators)
			r.Post("/upgrade-sets", routes_download.UpgradeSets)

			// Download Queue Routes
			r.Route("/queue", func(r chi.Router) {
				r.Get("/", routes_download.GetDownloadQueueStatus)
				r.Delete("/", routes_download.RemoveAllFromDownloadQueue)
				r.Get("/stream", routes_download.StreamDownloadQueueEvents)
				r.Get("/item", routes_download.GetAllDownloadQueueItems)
				r.Post("/item", routes_download.AddItemToDownloadQueue)
				r.Delete("/item", routes_download.RemoveItemFromDownloadQueue)
				r.Post("/item/top", routes_download.MoveDownloadQueueItemToTop)
			})

			// Download History Routes
			r.Route("/history", func(r chi.Router) {
				r.Get("/", routes_download.GetDownloadHistory)
				r.Delete("/", routes_download.RemoveAllDownloadHistory)
				r.Delete("/item", routes_download.RemoveDownloadHistoryEntry)
				r.Post("/retry", routes_download.RetryDownloadHistoryEntry)
			})
		})

		// Image Routes
		r.Route("/images", func(r chi.Router) {
			r.Get("/media/item", routes_images.GetMediaItemImage)
			r.Get("/media/collection", routes_images.GetCollectionItemImage)
			r.Get("/mediux/item", routes_images.GetMediuxImage)
			r.Get("/mediux/avatar", routes_images.GetMediuxAvatarImage)
			r.Delete("/temp", routes_images.DeleteTempImages)
		})

		// Jobs Routes
		r.Route("/jobs", func(r chi.Router) {
			r.Get("/", routes_jobs.GetAllJobs)
			r.Post("/", routes_jobs.RunJob)
		})

		// Statistics Route
		r.Get("/statistics", routes_statistics.GetStatistics)

		// Labels & Tags Route
		r.Post("/labels-tags", routes_labels_tags.ApplyLabelsAndTagsToItem)

		// Logging Routes
		r.Route("/logs", func(r chi.Router) {
			r.Get("/", routes_logging.GetLogContents)
			r.Delete("/", routes_logging.ClearLogFiles)
			r.Get("/debug-bundle", routes_logging.GetDebugBundle)
		})

		// Plex OAuth Routes
		r.Get("/oauth/plex", routes_plex.GetPlexPinAndID)
		r.Post("/oauth/plex", routes_plex.CheckAuthStatusWithPlex)

		// Media Server Routes
		r.Route("/mediaserver", func(r chi.Router) {
			r.Get("/libraries", routes_ms.GetLibrarySections)
			r.Post("/libraries/options", routes_ms.GetLibrarySectionOptions)
			r.Get("/library/items", routes_ms.GetLibraryItems)
			r.Get("/library/item/related", routes_ms.GetRelatedLibraryItems)
			r.Post("/library/refresh", routes_ms.RefreshLibrary)
			r.Get("/library/refresh/stream", routes_ms.StreamLibraryProgress)
			r.Get("/item", routes_ms.GetMediaItemDetails)
			r.Get("/collections", routes_ms.GetMovieCollections)
			r.Get("/collections/item", routes_ms.GetAllCollectionChildrenItems)
			r.Patch("/rate", routes_ms.RateMediaItem)
			r.Post("/refresh", routes_ms.RefreshMediaItemMetadata)
			r.Post("/sync", routes_ms.StartMediaServerSync)
			r.Get("/sync", routes_ms.GetMediaServerSync)
			r.Delete("/sync", routes_ms.StopMediaServerSync)
		})

		// MediUX Routes
		r.Route("/mediux", func(r chi.Router) {
			r.Get("/user", routes_mediux.GetUserFollowingAndHiding)
			r.Get("/set", routes_mediux.GetSetByID)
			r.Get("/sets/item", routes_mediux.GetItemSets)
			r.Get("/sets/user", routes_mediux.GetCreatorSets)
		})

		// Silo Plugin Routes, the download path is public and signed
		r.Route("/plugin/silo", func(r chi.Router) {
			r.Get("/status", routes_silo_plugin.GetStatus)
			r.Get("/images", routes_silo_plugin.GetImages)
			r.Get("/download/{token}", routes_silo_plugin.Download)
		})

		// Validation Routes
		r.Route("/validate", func(r chi.Router) {
			r.Post("/mediux", routes_validation.ValidateMediuxInfo)
			r.Post("/mediaserver", routes_validation.ValidateMediaServerInfo)
			r.Post("/sonarr", routes_validation.ValidateSonarrRadarrInfo)
			r.Post("/radarr", routes_validation.ValidateSonarrRadarrInfo)
			r.Post("/notifications", routes_validation.SendTestNotification)
		})
	})
}

func addOnboardingRoutes(r *chi.Mux) {

	r.Route("/api", func(r chi.Router) {

		// Protect setup mode with a login if auth is enabled, otherwise with the setup code from the logs
		r.Use(middleware.SetupGuard)

		// Base Routes
		r.Get("/", routes_base.HealthCheck)
		r.Get("/health", routes_base.HealthCheck)

		// Login - setup mode needs a login when auth is enabled
		r.Post("/login", routes_auth.AttemptLogin)
		r.Post("/logout", routes_auth.Logout)
		r.Get("/auth/oidc/login", routes_auth.OIDCLoginRedirect)
		r.Get("/auth/oidc/callback", routes_auth.OIDCCallback)

		// Setup Code
		r.Post("/setup/verify", routes_config.VerifySetupCode)

		// Config Routes
		r.Route("/config", func(r chi.Router) {
			r.Get("/", routes_config.GetSetupConfigStatus)
			r.Get("/stream", routes_config.StreamSetupConfigStatus)
			r.Get("/auth-methods", routes_auth.GetAuthMethods)
			r.Get("/template-variables", routes_config.GetNotificationTemplateVariables)
			r.Post("/", routes_config.UpdateAppConfig)
		})

		// Plex OAuth Routes
		r.Get("/oauth/plex", routes_plex.GetPlexPinAndID)
		r.Post("/oauth/plex", routes_plex.CheckAuthStatusWithPlex)

		// Logging Routes
		r.Route("/logs", func(r chi.Router) {
			r.Get("/", routes_logging.GetLogContents)
			r.Delete("/", routes_logging.ClearLogFiles)
			r.Get("/debug-bundle", routes_logging.GetDebugBundle)
		})

		r.Post("/mediaserver/libraries/options", routes_ms.GetLibrarySectionOptions)

		// Validation Routes
		r.Route("/validate", func(r chi.Router) {
			r.Post("/mediux", routes_validation.ValidateMediuxInfo)
			r.Post("/mediaserver", routes_validation.ValidateMediaServerInfo)
			r.Post("/sonarr", routes_validation.ValidateSonarrRadarrInfo)
			r.Post("/radarr", routes_validation.ValidateSonarrRadarrInfo)
			r.Post("/notifications", routes_validation.SendTestNotification)
			//r.Post("/database", routes_mediux.ValidateDatabaseInfo)
		})

		// Finalize Onboarding Route
		r.Post("/onboarding/finalize", func(w http.ResponseWriter, r *http.Request) {
			ctx, ld := logging.CreateLoggingContext(r.Context(), r.URL.Path)
			logAction := ld.AddAction("Finalize Onboarding", logging.LevelInfo)
			ctx = logging.WithCurrentAction(ctx, logAction)

			if !(config.Loaded && config.Valid) {
				logAction.SetError("Configuration is not valid or not loaded", "", nil)
				ld.Status = logging.StatusError
				httpx.SendResponse(w, ld, nil)
				return
			}

			triggered := false
			onboardingFinalizeOnce.Do(func() {
				triggered = true
				if OnboardingComplete != nil {
					logging.LOGGER.Info().Timestamp().Msg("Onboarding finalized, executing OnboardingComplete function")
					logging.Go("Onboarding Complete", OnboardingComplete)
				}
			})

			httpx.SendResponse(w, ld, map[string]any{
				"onboarding_finalized": triggered,
			})
		})
	})
}
